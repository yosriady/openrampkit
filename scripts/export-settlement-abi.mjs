// Writes packages/adapter/src/settlement-abi.ts from the Foundry build output.
//   cd contracts && forge build && cd .. && node scripts/export-settlement-abi.mjs
// A unit test fails when the committed ABI differs from contracts/out (when that folder exists).

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const artifact = JSON.parse(readFileSync(`${root}contracts/out/OpenRampSettlement.sol/OpenRampSettlement.json`, 'utf8'))
const out = `${root}packages/adapter/src/settlement-abi.ts`
const body = `// Generated by scripts/export-settlement-abi.mjs from contracts/src/OpenRampSettlement.sol. Do not edit.

/** ABI of OpenRampSettlement (for viem, ethers or any ABI-aware client) */
export const OPEN_RAMP_SETTLEMENT_ABI = ${JSON.stringify(artifact.abi, null, 2)} as const
`
writeFileSync(out, body)
console.log(`Wrote ${out} (${artifact.abi.length} entries)`)
